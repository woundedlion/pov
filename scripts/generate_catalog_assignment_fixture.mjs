/** Emits non-template setters whose bodies typecheck every catalog assignment. */
export function catalogAssignmentFixture(catalog) {
  const names = catalog.operators.map(operator => operator.id);
  if (new Set(names).size !== names.length || names.some(id => !FAMILIES[id]) ||
      Object.keys(FAMILIES).some(id => !names.includes(id)))
    throw new Error('The native assignment fixture and operator catalog differ');
  const lines = [
    '/*',
    ' * Required Notice: Copyright 2025 Gabriel Levy. All rights reserved.',
    ' * Licensed under the PolyForm Noncommercial License 1.0.0',
    ' */',
    '#pragma once', '',
    '/** @file generated_catalog_assignments.h',
    ' * @brief Native compilation of generated catalog parameter assignments. */', '',
    '// Generated by scripts/generate_catalog_assignment_fixture.mjs.',
    '// clang-format off',
  ];
  for (const operator of catalog.operators) {
    const document = { descriptor: { chain: [
      { label: 'authored', resource_key: 'native', operator: operator.id },
    ] } };
    const values = Object.fromEntries(operator.params.map(field => [`authored.${field.id}`, field.default]));
    const emit = assignments => {
      for (const [member, literal] of assignments) {
        if (!member.startsWith('native.')) throw new Error(`Unbound generated member: ${member}`);
        lines.push(`  params.${member.slice('native.'.length)} = ${literal};`);
      }
    };
    lines.push('', `inline void catalog_assignments_${operator.id.replaceAll(/[.-]/g, '_')}() {`,
      `  ${FAMILIES[operator.id]} params;`);
    emit(presetAssignments(document, values, { authoredTopology: true }));
    for (const field of operator.params.filter(field => field.topology))
      for (const choice of field.values)
        emit(presetAssignments(document, { [`authored.${field.id}`]: choice }, { authoredTopology: true }));
    lines.push('  (void)params;', '}');
  }
  lines.push('', '// clang-format on', '');
  return lines.join('\n');
}

if (isMain(import.meta.url)) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) {
    console.error('usage: generate_catalog_assignment_fixture.mjs [--check]');
    await exitAfterStderr(2);
  }
  const generated = catalogAssignmentFixture(await loadOperatorCatalog());
  if (process.argv.includes('--check')) {
    const committed = (await readFile(OUTPUT, 'utf8')).replaceAll('\r\n', '\n');
    if (committed !== generated) {
      console.error('Regenerate with: node scripts/generate_catalog_assignment_fixture.mjs');
      await exitAfterStderr(1);
    }
  } else await writeFile(OUTPUT, generated);
}
